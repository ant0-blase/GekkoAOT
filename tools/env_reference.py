"""Generate docs/ENVIRONMENT.md: every GEKKOAOT_* variable the sources read.

Usage: tools/env_reference.py [--check]

A variable is listed when a source file reads it (a getenv-style call with the
literal name, or a settings table). The component is the top-level directory
of the readers, the default is taken from the read call when it is a literal.
--check exits non-zero when the committed file is out of date.
"""
import argparse
import collections
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, 'docs', 'ENVIRONMENT.md')
SOURCES = ('*.cpp', '*.h', '*.hpp', '*.c', '*.py', 'CMakeLists.txt', '*.cmake')
NAME = re.compile(r'GEKKOAOT_[A-Z0-9_]+')
WRITE = re.compile(r'(env\.insert|env\.remove|SetEnvValue|setenv|unsetenv|qputenv|qunsetenv|'
                   r'_putenv_s|append_env)\s*\(\s*(std::string\()?["\']$')
DEFAULT = re.compile(r'"(GEKKOAOT_[A-Z0-9_]+)"\s*,\s*("[^"]*"|[-0-9.x\'a-fA-Fu]+|true|false)')
COMPONENTS = (
    ('src/', 'Launcher'),
    ('tools/', 'Controller and build tools'),
    ('runtime/gx/', 'Graphics'),
    ('runtime/dsp/', 'Audio and DSP'),
    ('runtime/os/', 'NativeOS'),
    ('runtime/hw/', 'Hardware services'),
    ('runtime/sdk/', 'SDK services'),
    ('runtime/perf/', 'Profiling'),
    ('runtime/', 'Runtime'),
)


def component(path):
    for prefix, label in COMPONENTS:
        if path.startswith(prefix):
            return label
    return 'Other'


def scan():
    out = subprocess.run(['git', 'grep', '-n', '-E', 'GEKKOAOT_[A-Z0-9_]+', '--'] + list(SOURCES),
                         cwd=ROOT, capture_output=True, text=True, check=True).stdout
    readers = collections.defaultdict(set)
    defaults = {}
    for line in out.splitlines():
        path, _, text = line.split(':', 2)
        if path == 'tools/env_reference.py' or path.startswith('tests/'):
            continue
        for match in NAME.finditer(text):
            name = match.group(0)
            before, after = text[:match.start()], text[match.end():]
            quoted = before.endswith(('"', "'")) and after.startswith(('"', "'"))
            if not quoted or WRITE.search(before):
                continue
            # A read passes the literal name as an argument or key, never
            # through a stream (log tags such as << "GEKKOAOT_STAGE").
            context = before[:-1].rstrip()
            if not context.endswith(('(', ',', '{', '[')) or context.endswith('<<'):
                continue
            readers[name].add(path)
        for match in DEFAULT.finditer(text):
            defaults.setdefault(match.group(1), match.group(2).strip('"'))
    return readers, defaults


def render(readers, defaults):
    groups = collections.defaultdict(list)
    for name, paths in readers.items():
        labels = sorted({component(p) for p in paths})
        groups[labels[0]].append((name, paths))
    lines = [
        '# Environment variables',
        '',
        'Generated by `tools/env_reference.py` from the sources; do not edit by hand.',
        'Every option the launcher exposes is also a per-game `config.ini` key and a',
        'variable listed here. Variables not set keep the default shown (an empty cell',
        'means the default is computed). Most entries are diagnostics or rollback',
        'switches for validated defaults; user-facing settings are described in',
        '[Graphics](GRAPHICS.md), [Launcher](LAUNCHER.md) and',
        '[Performance](OPTIMIZATIONS.md).',
        '',
        f'{len(readers)} variables.',
    ]
    for label in sorted(groups):
        lines += ['', f'## {label}', '', '| Variable | Default | Read in |', '| --- | --- | --- |']
        for name, paths in sorted(groups[label]):
            default = defaults.get(name, '')
            files = ', '.join(f'`{p}`' for p in sorted(paths)[:3])
            if len(paths) > 3:
                files += f' (+{len(paths) - 3})'
            lines.append(f'| `{name}` | {"`" + default + "`" if default else ""} | {files} |')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = render(*scan())
    if args.check:
        current = open(OUTPUT, encoding='utf-8').read() if os.path.exists(OUTPUT) else ''
        if current != text:
            print('docs/ENVIRONMENT.md is out of date; run tools/env_reference.py', file=sys.stderr)
            return 1
        return 0
    with open(OUTPUT, 'w', encoding='utf-8') as f:
        f.write(text)
    print(f'wrote {OUTPUT}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
