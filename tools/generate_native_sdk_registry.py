"""Generate all native SDK bindings from the runtime's authoritative service IDs.

A generated binding is availability metadata, not proof of recognition or
validation. Only exact resolver-admitted manifests activate it for a binary.
"""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'runtime/sdk/native_services.def'

def generate():
    resolver = (ROOT/'runtime/native/sdk_autoresolver.cpp').read_text()
    device = (ROOT/'runtime/native/device_sdk.def').read_text()
    runtime = (ROOT/'runtime/native/runtime.h').read_text()
    os = (ROOT/'runtime/os/native_os.h').read_text()
    devices = re.findall(r'DEVICE_SDK\((\w+),\s*"([^"]+)"\)', device)
    enum = re.search(r'enum class SimpleHleKind[^\{]*\{(.*?)\n\};', runtime, re.S)[1]
    enum = re.sub(r'//[^\n]*', '', enum)
    enum = re.sub(r'#define DEVICE_SDK.*?#undef DEVICE_SDK', ','.join(k for k,_ in devices)+',',enum,flags=re.S)
    kinds = [x.strip() for x in enum.split(',') if x.strip() and x.strip()!='Count']
    names = dict(devices)
    for condition,kind in re.findall(r'if\s*\((.*?)\)\s*return SimpleHleKind::(\w+);', resolver, re.S):
        candidates = re.findall(r'name\s*==\s*"([^"]+)"',condition)
        if candidates and kind not in names:names[kind]=candidates[0]
    missing = set(kinds)-names.keys()
    if missing:raise ValueError(f'Native services lack canonical names: {missing}')
    os_kinds = re.search(r'enum class Kind[^\{]*\{(.*?)\n\};',os,re.S)[1]
    os_kinds = [x.strip() for x in re.sub(r'//[^\n]*','',os_kinds).split(',') if x.strip() and x.strip()!='Count']
    os_names = dict(re.findall(r'case Kind::(\w+): return "([^"]+)";',os))
    context = set(re.findall(r'case OsKind::(\w+):',re.search(r'bool IsContextCaptureBoundary.*?\n}',resolver,re.S)[0]))
    rows = ['// SPDX-License-Identifier: GPL-3.0-or-later',
            '// Generated by tools/generate_native_sdk_registry.py. Do not edit.',
            '// Availability only. Per-binary recognition, admission and validation remain mandatory.']
    rows += [f'SDK_SIMPLE({kind}, "{names[kind]}", "leaf")' for kind in kinds]
    rows += [f'SDK_OS({kind}, "{os_names[kind]}", "'+('full-fp-context' if kind in context else 'leaf')+'")' for kind in os_kinds]
    if len(kinds)!=len(set(kinds)) or len(os_kinds)!=len(set(os_kinds)):raise ValueError('duplicate service IDs')
    return '\n'.join(rows)+'\n'

def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');args=ap.parse_args()
    text=generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text()!=text:raise SystemExit('stale NativeSDK registry: regenerate it')
    else:OUTPUT.write_text(text)
    print(f'NativeSDK registry: {sum(s.startswith("SDK_") for s in text.splitlines())} generated service bindings')
if __name__=='__main__':main()
